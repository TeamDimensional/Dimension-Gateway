output: list[str] = ["#reloadable", "# Autogenerated: do not edit manually", "import mods.modularmachinery.RecipeBuilder;"]

template = """RecipeBuilder.newBuilder("%(NAME)s_%(EXTRA)s", "dawnstone_refinery", 20)
    .addItemInput(<ore:ore%(NAME)s>)
    .addItemOutput(<item:jaopca:ore_cluster.%(CLUSTER1)s>)
    .addItemOutput(<item:jaopca:ore_cluster.%(CLUSTER2)s>).setChance(%(CHANCE)s)
    .addItemInput(<%(PICKAXE)s:*>).consumeDurability(1)
    .%(ASPECT_INPUT)s("%(ASPECT)s", 2)
    .setLoadJEI(%(LOAD_JEI)s)
    .addFluidInput(<fluid:%(FLUID)s> * 10)
    .build();"""

snake_case_regex = re.compile("([a-z])([A-Z])")


def generate_all():
    for ore, ore_info in ores.items():
        for i, (aspectInput, loadJEI) in enumerate(
            [("addAspectInput", False), ("addEssentiaInput", True)]
        ):
            for j, (pick, efficiency, byproduct) in enumerate(
                [
                    ("thaumcraft:elemental_pick", 0.4, ore_info.byproduct),
                    ("theaurorian:crystallinepickaxe", 0.2, ore),
                ]
            ):
                data = {
                    "NAME": ore,
                    "EXTRA": i + j * 10,
                    "CLUSTER1": snake_case_regex.sub(r"\1_\2", ore).lower(),
                    "CLUSTER2": snake_case_regex.sub(r"\1_\2", byproduct).lower(),
                    "CHANCE": efficiency,
                    "PICKAXE": pick,
                    "ASPECT_INPUT": aspectInput,
                    "ASPECT": ore_info.aspect,
                    "FLUID": ore_info.fluid,
                    "LOAD_JEI": str(loadJEI).lower(),
                }
                output.append(template % data)

    target = "minecraft/scripts/modularmachinery/dawnstone_refinery.zs"
    Path(target).write_text("\n\n".join(output))
